}

#───────────────────────────────────────────────────────────────────────────────
# MAIN COMMAND ROUTER
#───────────────────────────────────────────────────────────────────────────────

main() {
    local command="$1"
    shift
    
    case "$command" in
        # Initialization
        init)
            init_blackbox
            ;;
        
        # Session management
        start)
            start_session "$1" "$2"
            ;;
        end)
            end_session "$*"
            ;;
        status|stat|s)
            show_status
            ;;
        
        # Logging
        action|a)
            log_entry "ACTION" "$1" "$2"
            ;;
        decision|d)
            log_entry "DECISION" "$1" "$2"
            ;;
        issue|i)
            log_entry "ISSUE" "$1" "$2"
            ;;
        checkpoint|cp)
            checkpoint "$1"
            ;;
        milestone|m)
            log_entry "MILESTONE" "$1" ""
            ;;
        note|n)
            log_entry "NOTE" "$*" ""
            ;;
        
        # Catalog
        catalog|cat)
            rebuild_catalog
            ;;
        search)
            search_sessions "$1"
            ;;
        list|ls)
            ls -1t "$SESSIONS_DIR"/CONV-*.md 2>/dev/null | head -${1:-10} | while read f; do
                echo "  $(basename "$f" .md)"
            done
            ;;
        
        # Utilities
        id)
            generate_session_id "$1"
            ;;
        
        # Help
        help|--help|-h|"")
            show_help
            ;;
        
        *)
            print_error "Unknown command: $command"
            echo "Run './blackbox.sh help' for usage information"
            exit 1
            ;;
    esac
}

# Run main with all arguments
main "$@"
